/* ── Loading steps animation ─────────────────────────────────────────────── */
let stepTimer;
function startLoadingSteps() {
  const steps = document.querySelectorAll('.lstep');
  let current = 0;
  steps.forEach(s => s.classList.remove('active', 'done'));
  steps[0].classList.add('active');
  stepTimer = setInterval(() => {
    if (current < steps.length - 1) {
      steps[current].classList.remove('active');
      steps[current].classList.add('done');
      current++;
      steps[current].classList.add('active');
    }
  }, 2800);
}
function stopLoadingSteps() {
  clearInterval(stepTimer);
  document.querySelectorAll('.lstep').forEach(s => { s.classList.remove('active'); s.classList.add('done'); });
}

/* ── Visibility helpers ──────────────────────────────────────────────────── */
function showLoading()  { formCard.style.display = 'none'; oLoading.classList.remove('hidden'); }
function hideLoading()  { stopLoadingSteps(); oLoading.classList.add('hidden'); }
function showResults()  { oResults.classList.remove('hidden'); }
function showForm()     { formCard.style.display = ''; }
function setBusy(busy)  {
  startBtn.disabled = busy;
  startBtnTxt.textContent = busy ? 'Building…' : 'Build My Launch Plan →';
  startSpinner.classList.toggle('hidden', !busy);
}
function showError(msg) {
  errorBox.textContent = msg;
  errorBox.classList.remove('hidden');
  errorBox.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

/* ── RENDER ──────────────────────────────────────────────────────────────── */
function renderPlan(p) {
  const a = p.assets || {};
  renderIntro(p);
  renderSteps(p.steps);
  renderCategory(a);
  renderDescription(a.description);
  renderServices(a.services);
  renderPost(a.firstPost);
  renderQA(a.firstQA);
  renderPhotos(a.photoChecklist);
  renderChecklist(p.launchChecklist);
}

function renderIntro(p) {
  const readiness = (p.readiness || []).map(r => `<li>${esc(r)}</li>`).join('');
  document.getElementById('card-intro').innerHTML = `
    <div class="card-title"><span class="card-title-icon">👋</span> Welcome — Let's Get You on Google</div>
    <p class="st-intro-text">${esc(p.intro)}</p>
    <div class="st-meta-row">
      ${p.estimatedTime ? `<span class="st-meta">⏱ ${esc(p.estimatedTime)}</span>` : ''}
      <span class="st-meta">🧭 ${(p.steps || []).length} steps</span>
    </div>
    ${readiness ? `<div class="st-readiness"><div class="st-readiness-lbl">Have these ready</div><ul>${readiness}</ul></div>` : ''}
  `;
}

