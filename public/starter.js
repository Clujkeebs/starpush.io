/* ── State ───────────────────────────────────────────────────────────────── */
let lastPlan = null;

/* ── DOM refs ────────────────────────────────────────────────────────────── */
const startBtn    = document.getElementById('start-btn');
const startBtnTxt = document.getElementById('start-btn-txt');
const startSpinner= document.getElementById('start-spinner');
const errorBox    = document.getElementById('f-error');
const formCard    = document.getElementById('form-card');
const oLoading    = document.getElementById('o-loading');
const oResults    = document.getElementById('o-results');
const loadingBiz  = document.getElementById('loading-biz');

/* ── Form submit ─────────────────────────────────────────────────────────── */
startBtn.addEventListener('click', async () => {
  errorBox.classList.add('hidden');

  const name     = document.getElementById('f-name').value.trim();
  const category = document.getElementById('f-category').value;
  const city     = document.getElementById('f-city').value.trim();
  const services = document.getElementById('f-services').value.trim();
  const hasProfile = document.querySelector('input[name="hasProfile"]:checked').value === 'yes';

  if (!name)     { showError('Business name is required.'); return shake(document.getElementById('f-name')); }
  if (!category) { showError('Please select your trade / category.'); return shake(document.getElementById('f-category')); }
  if (!city)     { showError('City is required.'); return shake(document.getElementById('f-city')); }

  setBusy(true);
  loadingBiz.textContent = name;
  startLoadingSteps();
  showLoading();

  try {
    const res  = await fetch('/api/gbp-starter', {
      method:  'POST',
      headers: { 'Content-Type': 'application/json' },
      body:    JSON.stringify({
        businessName: name, category, city, services, hasProfile,
        email: document.getElementById('f-email')?.value.trim() || '',
      }),
    });
    const data = await res.json();
    if (!res.ok) throw new Error(data.error || 'Could not build your plan. Please try again.');

    lastPlan = data.plan;
    renderPlan(data.plan);
    hideLoading();
    showResults();
    window.scrollTo({ top: oResults.offsetTop - 20, behavior: 'smooth' });
  } catch (err) {
    hideLoading();
    showForm();
    // See optimize.js — a shape mismatch from the model shouldn't surface as a
    // raw JS error to the business owner.
    const isRenderError = err instanceof TypeError;
    if (isRenderError) console.error('[Starter] render failed:', err);
    showError(isRenderError
      ? 'The AI returned an incomplete plan. Please hit the button again — this usually works on the second try.'
      : err.message);
  } finally {
    setBusy(false);
  }
});

/* Start over */
document.getElementById('restart-btn').addEventListener('click', () => {
  oResults.classList.add('hidden');
  showForm();
  window.scrollTo({ top: 0, behavior: 'smooth' });
});

